function decodeHtmlDataUrl(value?: string): string {
  const prefix = 'data:text/html;charset=utf-8;base64,';
  if (!value || !value.startsWith(prefix)) return '';
  try {
    const binary = window.atob(value.slice(prefix.length));
    const bytes = Uint8Array.from(binary, (character) => character.charCodeAt(0));
    return new TextDecoder().decode(bytes);
  } catch {
    return '';
  }
}

const WebsiteBuilder: React.FC = () => {
  const [searchParams] = useSearchParams();
  const language = (localStorage.getItem('language') || 'en').startsWith('fa') ? 'fa' : 'en';
  const t = copy[language];
  const [name, setName] = useState('');
  const [tagline, setTagline] = useState('');
  const [brief, setBrief] = useState(() => searchParams.get('prompt') || '');
  const [featuresText, setFeaturesText] = useState('');
  const [contactEmail, setContactEmail] = useState('');
  const [kind, setKind] = useState<SiteKind>('business');
  const [palette, setPalette] = useState<Palette>('midnight');
  const [html, setHtml] = useState('');
  const [tab, setTab] = useState<'preview' | 'code'>('preview');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [status, setStatus] = useState('');
  const [jobId, setJobId] = useState('');
  const direction = language === 'fa' ? 'rtl' : 'ltr';

  const previewDocument = useMemo(
    () => html || '<!doctype html><html><body style="font-family:system-ui;padding:40px;background:#080b18;color:white"><h1>SINA Website Builder</h1><p>Build your first website draft.</p></body></html>',
    [html],
  );

  const build = async () => {
    setError('');
    setStatus('');
    setJobId('');
    if (!name.trim()) { setError(t.nameRequired); return; }
    if (!tagline.trim()) { setError(t.taglineRequired); return; }
    if (!brief.trim()) { setError(t.briefRequired); return; }
    if (contactEmail.trim() && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(contactEmail.trim())) {
      setError(t.emailInvalid);
      return;
    }

    setLoading(true);
    setStatus(t.submitting);
    try {
      const features = featuresText.split('\\n').map((line) => line.trim()).filter(Boolean).map((line) => {
        const separator = line.indexOf('|');
        return separator < 0
          ? { title: line, description: brief.trim() }
          : { title: line.slice(0, separator).trim(), description: line.slice(separator + 1).trim() };
      });
      if (features.length > 6 || features.some((feature) => !feature.title || !feature.description)) {
        throw new Error('Add at most six sections, each with a title and description.');
      }
      const created = await apiClient.createWebsiteJob({
        name: name.trim(),
        tagline: tagline.trim(),
        description: brief.trim(),
        kind,
        palette,
        language: language as 'en' | 'fa',
        ...(features.length ? { features } : {}),
        ...(contactEmail.trim() ? { contactEmail: contactEmail.trim() } : {}),
      });
      const nextJobId = created.data?.jobId;
      if (!created.success || !nextJobId) {
        throw new Error(created.error?.message || t.failed);
      }
      setJobId(nextJobId);
      setStatus(t.queued);

      const deadline = Date.now() + 120000;
      let firstPoll = true;
      while (Date.now() < deadline) {
        if (!firstPoll) await new Promise((resolve) => window.setTimeout(resolve, 1200));
        firstPoll = false;
        const polled = await apiClient.getJobStatus(nextJobId);
        const job = polled.data;
        if (!polled.success || !job) {
          throw new Error(polled.error?.message || t.failed);
        }
        if (job.status === 'completed') {
          const generatedHtml = String(
            job.result?.metadata?.html
            || job.output?.metadata?.html
            || decodeHtmlDataUrl(job.result?.contentUrl || job.output?.url)
            || '',
          );
          if (!generatedHtml.startsWith('<!doctype html>')) {
            throw new Error('The job completed but no valid HTML artifact was returned.');
          }
          setHtml(generatedHtml);
          setTab('preview');
          setStatus(t.completed);
          return;
        }
        if (job.status === 'failed' || job.status === 'cancelled') {
          throw new Error(job.error?.message || t.failed);
        }
        setStatus(job.status === 'processing' ? t.processing : t.queued);
      }
      throw new Error(t.timeout);
    } catch (err) {
      setError(err instanceof Error ? err.message : t.failed);
      setStatus('');
    } finally {
      setLoading(false);
    }
  };

  const download = () => {
    if (!html) return;
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = (name.trim() || 'sina-website').toLowerCase().replace(/[^a-z0-9-]+/g, '-') + '.html';
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return (
    <Container maxWidth="xl" className="website-builder" dir={direction} sx={{ py: { xs: 2, md: 4 } }}>
      <Stack spacing={1} sx={{ mb: 3 }}>
        <Chip label={t.eyebrow} color="info" variant="outlined" sx={{ alignSelf: 'flex-start', letterSpacing: 1 }} />
        <Typography variant="h3" fontWeight={800}>{t.title}</Typography>
        <Typography color="text.secondary">{t.subtitle}</Typography>
      </Stack>
      <Alert severity="info" sx={{ mb: 3 }}>{t.honest}</Alert>
      {error && <Alert severity="error" sx={{ mb: 2 }}>{error}</Alert>}
      {status && (
        <Alert severity={status === t.completed ? 'success' : 'info'} sx={{ mb: 2 }}>
          {status}{jobId ? ' · ' + t.job + ': ' + jobId : ''}
        </Alert>
      )}
      <Grid container spacing={3}>
        <Grid item xs={12} md={4}>
          <Paper className="website-builder-panel" sx={{ p: { xs: 2, md: 3 } }}>
            <Stack spacing={2}>
              <TextField label={t.name} value={name} onChange={(e) => setName(e.target.value)} fullWidth disabled={loading} inputProps={{ maxLength: 70 }} />
              <TextField label={t.tagline} value={tagline} onChange={(e) => setTagline(e.target.value)} fullWidth disabled={loading} inputProps={{ maxLength: 160 }} />
              <TextField label={t.brief} value={brief} onChange={(e) => setBrief(e.target.value)} fullWidth multiline minRows={4} disabled={loading} inputProps={{ maxLength: 2000 }} />
              <TextField label={t.features} value={featuresText} onChange={(e) => setFeaturesText(e.target.value)} fullWidth multiline minRows={3} disabled={loading} inputProps={{ maxLength: 3600 }} helperText={language === 'fa' ? 'نمونه: خدمات طراحی | طراحی سایت و هویت بصری' : 'Example: Design services | Websites and visual identity'} />
              <TextField label={t.email} type="email" value={contactEmail} onChange={(e) => setContactEmail(e.target.value)} fullWidth disabled={loading} inputProps={{ maxLength: 254 }} />
              <TextField select label={t.kind} value={kind} onChange={(e) => setKind(e.target.value as SiteKind)} disabled={loading}>
                <MenuItem value="portfolio">{t.portfolio}</MenuItem>
                <MenuItem value="business">{t.business}</MenuItem>
                <MenuItem value="product">{t.product}</MenuItem>
              </TextField>
              <TextField select label={t.palette} value={palette} onChange={(e) => setPalette(e.target.value as Palette)} disabled={loading}>
                <MenuItem value="midnight">{t.midnight}</MenuItem>
                <MenuItem value="light">{t.light}</MenuItem>
                <MenuItem value="ocean">{t.ocean}</MenuItem>
              </TextField>
              <Button variant="contained" size="large" onClick={() => void build()} disabled={loading} startIcon={<CodeRoundedIcon />}>
                {loading ? t.processing : t.generate}
              </Button>
            </Stack>
          </Paper>
        </Grid>
        <Grid item xs={12} md={8}>
          <Paper className="website-builder-preview" sx={{ overflow: 'hidden' }}>
            <Stack direction="row" alignItems="center" justifyContent="space-between" sx={{ p: 2, borderBottom: 1, borderColor: 'divider' }}>
              <Stack direction="row" spacing={1}>
                <Button size="small" variant={tab === 'preview' ? 'contained' : 'text'} onClick={() => setTab('preview')} startIcon={<VisibilityRoundedIcon />}>{t.preview}</Button>
                <Button size="small" variant={tab === 'code' ? 'contained' : 'text'} onClick={() => setTab('code')} startIcon={<CodeRoundedIcon />}>{t.source}</Button>
              </Stack>
              <Button size="small" variant="outlined" disabled={!html} onClick={download} startIcon={<DownloadRoundedIcon />}>{t.download}</Button>
            </Stack>
            {tab === 'preview'
              ? <div className="website-builder-frame"><iframe title="Website live preview" srcDoc={previewDocument} sandbox="" /></div>
              : <div style={{ padding: 16 }}><Typography variant="caption" color="text.secondary">{t.editHint}</Typography><TextField value={html} onChange={(e) => setHtml(e.target.value)} multiline minRows={24} fullWidth dir="ltr" sx={{ mt: 2, '& textarea': { fontFamily: 'monospace', fontSize: 12 } }} /></div>}
            {!html && <Typography color="text.secondary" sx={{ p: 3 }}>{t.draft}</Typography>}
          </Paper>
        </Grid>
      </Grid>
    </Container>
  );
};

export default WebsiteBuilder;
